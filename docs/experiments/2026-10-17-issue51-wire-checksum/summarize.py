#!/usr/bin/env python3
"""Recompute report tables from committed rows; never modify raw observations.

Microbenchmarks report median times and the arithmetic mean of paired percent
changes. Packet-pump/TUN report medians and median paired percent changes.
Percentile bootstrap CIs resample whole blocks (2000 draws, stable per-metric
seed). These are descriptive intervals, not equivalence/non-inferiority tests.
Run without arguments to write summaries/tables; --check verifies reproducibility.
"""
import argparse
import hashlib
import json
from pathlib import Path
import random
import statistics as st

ROOT = Path(__file__).resolve().parent


def rows(name):
    return [json.loads(line) for line in (ROOT / name).read_text().splitlines() if line]


def ci(values, statistic, key):
    rng = random.Random(int.from_bytes(hashlib.sha256(key.encode()).digest()[:8], "big"))
    draws = sorted(statistic(rng.choices(values, k=len(values))) for _ in range(2000))
    return [draws[50], draws[1950]]


def change(base, cand):
    return [(c / b - 1) * 100 for b, c in zip(base, cand)]


def interval(v):
    return f"[{v[0]:+.2f}, {v[1]:+.2f}]"


def micro(raw, key):
    result = {}
    for case in dict.fromkeys(r["case"] for r in raw):
        rs = [r for r in raw if r["case"] == case]
        b, c, a = ([r[k] for r in rs] for k in ("base_ns", "cand_ns", "aa_ns"))
        ab, aa = change(b, c), change(b, a)
        result[case] = dict(base_ns=st.median(b), cand_ns=st.median(c),
            ab_pct=st.mean(ab), ab_ci=ci(ab, st.mean, key + case + "ab"),
            wins=f"{sum(y < x for x, y in zip(b, c))}/{len(rs)}",
            aa_pct=st.mean(aa), aa_ci=ci(aa, st.mean, key + case + "aa"))
    return result


def pump(raw, key):
    result = {}
    for case in dict.fromkeys(r["scenario"] for r in raw):
        rs = [r for r in raw if r["scenario"] == case]
        b, c, a = ([r[k]["work_process_cpu_sec_per_GB"] for r in rs] for k in ("base", "cand", "aa"))
        ab, aa = change(b, c), change(b, a)
        counts = {r[k]["wire_packets"] for r in rs for k in ("base", "cand", "aa")}
        result[case] = dict(wire_packets_min=min(counts), wire_packets_max=max(counts),
            base_cpu_s_per_gb_median=st.median(b), cand_cpu_s_per_gb_median=st.median(c),
            ab_cpu_pct_median=st.median(ab), ab_cpu_ci95_pct=ci(ab, st.median, key + case + "ab"),
            cand_wins=sum(y < x for x, y in zip(b, c)), aa_cpu_pct_median=st.median(aa),
            aa_cpu_ci95_pct=ci(aa, st.median, key + case + "aa"),
            ab_wall_gbps_pct_median=st.median(change(
                [r["base"]["work_wall_Gbit_per_sec"] for r in rs],
                [r["cand"]["work_wall_Gbit_per_sec"] for r in rs])))
    return result


def tables(micros, pumps):
    lines = ["<!-- Generated by summarize.py; changes are paired percentages. -->", ""]
    for arch, data in micros.items():
        lines += [f"### {arch} microbenchmarks", "",
            "| Case | Base median ns | Candidate median ns | AB mean % [95% CI] | Wins | AA mean % [95% CI] |",
            "|---|---:|---:|---|---:|---|"]
        for case, v in data.items():
            lines.append(f"| `{case}` | {v['base_ns']:.3f} | {v['cand_ns']:.3f} | {v['ab_pct']:+.2f} {interval(v['ab_ci'])} | {v['wins']} | {v['aa_pct']:+.2f} {interval(v['aa_ci'])} |")
        lines.append("")
    for arch, data in pumps.items():
        lines += [f"### {arch} packet-pump", "",
            "| Case | Packet count range | Base median CPU s/GB | Candidate median CPU s/GB | AB median % [95% CI] | Wins / 6 | AA median % [95% CI] |",
            "|---|---:|---:|---:|---|---:|---|"]
        for case, v in data.items():
            lines.append(f"| `{case}` | {v['wire_packets_min']}–{v['wire_packets_max']} | {v['base_cpu_s_per_gb_median']:.4f} | {v['cand_cpu_s_per_gb_median']:.4f} | {v['ab_cpu_pct_median']:+.2f} {interval(v['ab_cpu_ci95_pct'])} | {v['cand_wins']} | {v['aa_cpu_pct_median']:+.2f} {interval(v['aa_cpu_ci95_pct'])} |")
        lines.append("")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    micros, pumps, outputs = {}, {}, {}
    for arch, name in [("x86_64-default", "rows-pcore-clean.jsonl"),
                       ("x86_64-native", "rows-pcore-native.jsonl"),
                       ("aarch64", "aarch64-rows.jsonl")]:
        micros[arch] = micro(rows(name), arch)
        outputs[arch + "-summary.json"] = json.dumps(micros[arch], indent=2) + "\n"
    for arch in ("x86_64", "aarch64"):
        pumps[arch] = pump(rows("pump-" + arch + "-rows.jsonl"), arch)
        outputs["pump-" + arch + "-summary.json"] = json.dumps(pumps[arch], indent=2) + "\n"
    outputs["tables.md"] = tables(micros, pumps)
    stale = []
    for name, content in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(name)
        else:
            path.write_text(content)
    if stale:
        raise SystemExit("Stale generated reports: " + ", ".join(stale))
    print("Verified" if args.check else "Wrote", len(outputs), "derived files; raw rows unchanged")


if __name__ == "__main__":
    main()
